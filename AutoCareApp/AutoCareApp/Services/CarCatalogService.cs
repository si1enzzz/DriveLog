    // Список всех марок в алфавитном порядке
    public static IReadOnlyList<string> PopularBrands => Catalog.Keys.OrderBy(x => x).ToList();

    // Получить список моделей для выбранной марки (нечувствительно к регистру и вхождениям)
    public static IReadOnlyList<string> GetModelsForBrand(string? brand)
    {
        if (string.IsNullOrWhiteSpace(brand)) return Array.Empty<string>();

        var clean = brand.Trim();
        var match = Catalog.Keys.FirstOrDefault(k => 
            k.Equals(clean, StringComparison.OrdinalIgnoreCase) ||
            k.IndexOf(clean, StringComparison.OrdinalIgnoreCase) >= 0 ||
            clean.IndexOf(k, StringComparison.OrdinalIgnoreCase) >= 0);

        if (match != null && Catalog.TryGetValue(match, out var models))
        {
            return models.Select(m => m.Name).ToList();
        }

        return Array.Empty<string>();
    }

    // Получить список поколений для выбранной марки и модели
    public static IReadOnlyList<string> GetGenerationsForModel(string? brand, string? model)
    {
        if (string.IsNullOrWhiteSpace(brand) || string.IsNullOrWhiteSpace(model)) 
            return Array.Empty<string>();

        var cleanBrand = brand.Trim();
        var cleanModel = model.Trim();

        var matchBrand = Catalog.Keys.FirstOrDefault(k => 
            k.Equals(cleanBrand, StringComparison.OrdinalIgnoreCase) ||
            k.IndexOf(cleanBrand, StringComparison.OrdinalIgnoreCase) >= 0 ||
            cleanBrand.IndexOf(k, StringComparison.OrdinalIgnoreCase) >= 0);

        if (matchBrand != null && Catalog.TryGetValue(matchBrand, out var models))
        {
            var matchModel = models.FirstOrDefault(m => 
                m.Name.Equals(cleanModel, StringComparison.OrdinalIgnoreCase) ||
                m.Name.IndexOf(cleanModel, StringComparison.OrdinalIgnoreCase) >= 0 ||
                cleanModel.IndexOf(m.Name, StringComparison.OrdinalIgnoreCase) >= 0);

            if (matchModel != null)
            {
                return matchModel.Generations;
            }
        }

        return Array.Empty<string>();
    }
